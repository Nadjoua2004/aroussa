async function seedBoutiques() {
  const supabase = getSupabaseClient();
  if (!supabase) {
    console.error('❌ Supabase non configuré.');
    process.exit(1);
  }

  console.log('🌸 1. Mise à jour des sous-catégories de tenues...');
  const { error: subErr } = await supabase
    .from('dress_subcategories')
    .upsert(DRESS_SUBCATEGORIES, { onConflict: 'slug' });
  if (subErr) {
    console.error('Erreur sous-catégories:', subErr.message);
  }

  console.log('🌸 2. Insertion des 34 boutiques réelles dans Supabase...');
  let insertedCount = 0;

  for (const b of REAL_BOUTIQUES) {
    const shopRow = {
      category_id: CATEGORY_TENUES_ID,
      name: b.name,
      slug: b.slug,
      description: b.description,
      service_mode: b.service_mode,
      offers_buy: b.offers_buy,
      offers_rent: b.offers_rent,
      shop_type: b.shop_type,
      is_physical: b.is_physical,
      is_online: b.is_online,
      wilaya_code: b.wilaya_code,
      city_commune: b.city_commune,
      address: b.address,
      google_maps_url: b.google_maps_url,
      latitude: b.latitude || null,
      longitude: b.longitude || null,
      phone: b.phone,
      whatsapp: b.whatsapp,
      instagram_handle: b.instagram_handle,
      instagram_url: b.instagram_url,
      facebook_url: b.facebook_url || null,
      tiktok_url: b.tiktok_url || null,
      website_url: b.website_url || null,
      is_verified: b.is_verified,
      sponsored_rank: 35 - b.order, // conserve l'ordre 1 à 34 du PDF
      status: 'published',
      updated_at: new Date().toISOString(),
    };

    const { data: savedShop, error: shopErr } = await supabase
      .from('shops')
      .upsert(shopRow, { onConflict: 'slug' })
      .select('id, name, slug')
      .single();

    if (shopErr) {
      console.error(`❌ Erreur pour ${b.name}:`, shopErr.message);
      continue;
    }

    // Liaison avec les sous-catégories
    await supabase.from('shop_subcategories').delete().eq('shop_id', savedShop.id);

    const subLinks = (b.subcategories || [])
      .map((slug) => {
        const sub = DRESS_SUBCATEGORIES.find((s) => s.slug === slug);
        return sub ? { shop_id: savedShop.id, subcategory_id: sub.id } : null;
      })
      .filter(Boolean);

    if (subLinks.length > 0) {
      await supabase.from('shop_subcategories').insert(subLinks);
    }

    insertedCount++;
    console.log(`  ✓ [${b.order}/34] ${b.name} (${b.instagram_handle})`);
  }

  console.log(`\n✨ Terminé : ${insertedCount}/34 boutiques intégrées avec succès dans Supabase !`);
}

seedBoutiques();

